-- V16: Payment QR + Billing tables + Price Quote (deal giá) + Additional Cost
-- Thêm trạng thái DEPOSIT_PAID vào repair_requests.status CHECK nếu cần
-- (PostgreSQL enum string nên không cần ALTER TYPE)

-- Bảng deal giá (thợ gửi báo giá cạnh tranh, khách chọn)
CREATE TABLE IF NOT EXISTS price_quotes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       BIGINT NOT NULL REFERENCES repair_requests(id) ON DELETE CASCADE,
    technician_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    quoted_price     DECIMAL(15, 0) NOT NULL,
    note             TEXT,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                         CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED')),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       BIGINT,
    updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by       BIGINT,
    deleted_at       TIMESTAMP,
    deleted_by       BIGINT,
    CONSTRAINT uq_price_quote_tech_request UNIQUE (request_id, technician_id)
);

CREATE INDEX IF NOT EXISTS idx_price_quotes_request ON price_quotes(request_id);
CREATE INDEX IF NOT EXISTS idx_price_quotes_technician ON price_quotes(technician_id);

-- Bảng chi phí phát sinh (thợ đăng, khách duyệt)
CREATE TABLE IF NOT EXISTS additional_costs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       BIGINT NOT NULL REFERENCES repair_requests(id) ON DELETE CASCADE,
    description      TEXT NOT NULL,
    amount           DECIMAL(15, 0) NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                         CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    approved_at      TIMESTAMP,
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       BIGINT,
    updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by       BIGINT,
    deleted_at       TIMESTAMP,
    deleted_by       BIGINT
);

CREATE INDEX IF NOT EXISTS idx_additional_costs_request ON additional_costs(request_id);

-- Bảng thanh toán (đặt cọc 30% + thanh toán tổng cuối)
CREATE TABLE IF NOT EXISTS payments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id        BIGINT NOT NULL REFERENCES repair_requests(id) ON DELETE CASCADE,
    payment_type      VARCHAR(20) NOT NULL CHECK (payment_type IN ('DEPOSIT', 'FINAL')),
    amount            DECIMAL(15, 0) NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                          CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    transfer_content  VARCHAR(50),
    qr_url            TEXT,
    confirmed_at      TIMESTAMP,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by        BIGINT,
    updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by        BIGINT,
    deleted_at        TIMESTAMP,
    deleted_by        BIGINT
);

CREATE INDEX IF NOT EXISTS idx_payments_request ON payments(request_id);
CREATE INDEX IF NOT EXISTS idx_payments_status ON payments(status);

-- Bảng hóa đơn (bill) — xuất sau khi thanh toán confirmed
CREATE TABLE IF NOT EXISTS bills (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_number       VARCHAR(30) NOT NULL UNIQUE,
    payment_id        BIGINT NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
    bill_type         VARCHAR(20) NOT NULL CHECK (bill_type IN ('DEPOSIT', 'FINAL')),
    customer_name     VARCHAR(255),
    customer_phone    VARCHAR(20),
    customer_address  TEXT,
    technician_name   VARCHAR(255),
    technician_phone  VARCHAR(20),
    service_category  VARCHAR(100),
    service_description TEXT,
    request_id        BIGINT NOT NULL REFERENCES repair_requests(id) ON DELETE CASCADE,
    quoted_price      DECIMAL(15, 0) NOT NULL DEFAULT 0,
    deposit_amount    DECIMAL(15, 0) NOT NULL DEFAULT 0,
    additional_cost   DECIMAL(15, 0) NOT NULL DEFAULT 0,
    total_amount      DECIMAL(15, 0) NOT NULL,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by        BIGINT,
    updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by        BIGINT,
    deleted_at        TIMESTAMP,
    deleted_by        BIGINT
);

CREATE INDEX IF NOT EXISTS idx_bills_payment ON bills(payment_id);
CREATE INDEX IF NOT EXISTS idx_bills_request ON bills(request_id);

-- Sequence tránh race condition khi sinh mã hóa đơn đồng thời
CREATE SEQUENCE IF NOT EXISTS bill_daily_seq START WITH 1 INCREMENT BY 1;
