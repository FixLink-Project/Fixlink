-- =============================================================================
-- FIXLINK - QUẢN LÝ PHIẾU HỖ TRỢ KHÁCH HÀNG (SUPPORT TICKETS)
-- =============================================================================

CREATE TABLE IF NOT EXISTS support_tickets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code   VARCHAR(50)  NOT NULL UNIQUE,
    user_id       BIGINT,
    guest_name    VARCHAR(100),
    guest_contact VARCHAR(100),
    title         VARCHAR(255) NOT NULL,
    description   TEXT         NOT NULL,
    priority      VARCHAR(20)  NOT NULL DEFAULT 'Medium',
    status        VARCHAR(20)  NOT NULL DEFAULT 'Open',
    assignee      VARCHAR(100) NOT NULL DEFAULT 'Chưa phân công',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_support_tickets_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_support_tickets_code ON support_tickets (ticket_code);
CREATE INDEX IF NOT EXISTS idx_support_tickets_user_id ON support_tickets (user_id);
CREATE INDEX IF NOT EXISTS idx_support_tickets_status ON support_tickets (status);
