-- 3. Bảng QUOTATIONS (Báo giá từ thợ)
CREATE TABLE IF NOT EXISTS quotations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id          BIGINT       NOT NULL,
    technician_id       BIGINT       NOT NULL,
    solution            TEXT         NOT NULL,
    price_labor_vnd     DECIMAL(12,0) NOT NULL DEFAULT 0,
    price_materials_vnd DECIMAL(12,0) NOT NULL DEFAULT 0,
    inspection_time     TIMESTAMP WITH TIME ZONE,
    estimated_finish    TIMESTAMP WITH TIME ZONE,
    note                TEXT,
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          BIGINT,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          BIGINT,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    deleted_by          BIGINT,
    CONSTRAINT fk_quotation_request    FOREIGN KEY (request_id)    REFERENCES repair_requests(id),
    CONSTRAINT fk_quotation_technician FOREIGN KEY (technician_id) REFERENCES users(id),
    CONSTRAINT uq_quotation_tech_request UNIQUE (request_id, technician_id)
);
CREATE INDEX IF NOT EXISTS idx_quotations_request    ON quotations(request_id);
CREATE INDEX IF NOT EXISTS idx_quotations_technician ON quotations(technician_id);
CREATE INDEX IF NOT EXISTS idx_quotations_status     ON quotations(status);

-- 4. Bảng MEDIA (hình ảnh đính kèm)
CREATE TABLE IF NOT EXISTS media (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type VARCHAR(30)  NOT NULL,
    owner_id   BIGINT       NOT NULL,
    url        VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT
);
CREATE INDEX IF NOT EXISTS idx_media_owner ON media(owner_type, owner_id);

-- 5. Bảng WORK_PROGRESS (lịch sử chuyển trạng thái)
CREATE TABLE IF NOT EXISTS work_progress (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT      NOT NULL,
    from_status VARCHAR(30) NOT NULL,
    to_status   VARCHAR(30) NOT NULL,
    note        TEXT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  BIGINT,
    CONSTRAINT fk_work_progress_request FOREIGN KEY (request_id) REFERENCES repair_requests(id)
);
CREATE INDEX IF NOT EXISTS idx_work_progress_request ON work_progress(request_id);
